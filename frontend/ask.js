  // -- speaking --------------------------------------------------------------------------------
  // An answer is spoken a sentence or two at a time (speechChunks). Every utterance is held in
  // `speechQueue` until it ends: Chrome can collect one nobody refers to and stop mid-word.

  var LANG = speechLang(root.navigator && root.navigator.language);
  var synth = root.speechSynthesis && root.SpeechSynthesisUtterance ? root.speechSynthesis : null;
  var speechQueue = [];
  var speechTimer = 0;
  var speechUnlocked = false;
  var blockedSpeech = ""; // an answer the browser refused to speak until the next tap
  var voice = null;

  function chooseVoice() {
    if (synth) {
      voice = pickVoice(synth.getVoices(), LANG);
    }
  }

  function stopSpeaking() {
    root.clearTimeout(speechTimer);
    speechQueue = [];
    // Cancel only what is there: Chrome can drop the next utterance after a needless cancel().
    if (synth && (synth.speaking || synth.pending)) {
      synth.cancel();
    }
  }

  // Speaks whatever it is given, muted or not (the voice test uses it directly).
  // `onDone` (optional) is called once, when the last piece has been spoken (or failed), so the
  // voice test can start listening after its sample and not over it: listening cancels speech.
  function say(text, onDone) {
    if (!synth) {
      return false;
    }
    stopSpeaking();
    var chunks = speechChunks(text, SPEECH_CHUNK_CHARS);
    if (!chunks.length) {
      return false;
    }
    var done = false;
    function finish() {
      if (!done) {
        done = true;
        if (onDone) {
          onDone();
        }
      }
    }
    if (!voice) {
      chooseVoice();
    }
    // On the next tick, never in the same one as cancel(): Chrome drops that utterance.
    speechTimer = root.setTimeout(function () {
      chunks.forEach(function (chunk, position) {
        var utterance = new root.SpeechSynthesisUtterance(chunk);
        utterance.lang = LANG;
        if (voice) {
          utterance.voice = voice;
        }
        utterance.onend = utterance.onerror = function (event) {
          var index = speechQueue.indexOf(utterance);
          if (index >= 0) {
            speechQueue.splice(index, 1);
          }
          if (event && event.type === "error" && event.error === "not-allowed") {
            // The browser wants a tap before it will speak (iOS): keep the answer, and say it
            // when the operator next taps or clicks anything (unlockSpeech).
            blockedSpeech = text;
            speechUnlocked = false;
            status.textContent = "Tap anywhere on the page to hear the answer.";
          }
          if (position === chunks.length - 1) {
            finish();
          }
        };
        speechQueue.push(utterance);
        synth.speak(utterance);
      });
    }, SPEECH_DELAY_MS);
    // A browser that never reports the end must not leave the caller waiting for ever.
    root.setTimeout(finish, SPEECH_DONE_FALLBACK_MS);
    return true;
  }

  function speak(text) {
    if (muted || !text) {
      return;
    }
    say(text);
  }

  // iOS speaks only if speech was first started from a tap; an answer arrives seconds after one.
  // The first tap on a control (not the talk button, whose tap starts the microphone) speaks one
  // silent space, and later answers are then allowed.
  //
  // On click (and Enter or Space), not pointerdown: a touch's pointerdown is not a user activation,
  // so iOS would refuse the very utterance meant to unlock it. Not on the talk button, whose tap
  // starts the microphone. Marked done only when the silent utterance actually starts; an answer
  // that was refused in the meantime (blockedSpeech) is spoken now, from this tap.
  function unlockSpeech(event) {
    if (!synth || (event && event.target && event.target.closest && event.target.closest("#ask-talk"))) {
      return;
    }
    if (blockedSpeech) {
      var text = blockedSpeech;
      blockedSpeech = "";
      speechUnlocked = true;
      speak(text);
      return;
    }
    if (speechUnlocked) {
      return;
    }
    var silent = new root.SpeechSynthesisUtterance(" ");
    silent.volume = 0;
    silent.onstart = function () {
      speechUnlocked = true;
    };
    synth.speak(silent);
  }

  // Back to the gate: forgets the token and the conversation.
  function showGate(message) {
    accessToken = null;
    tokenExpiresAt = 0;
    turns = [];
    stopSpeaking();
    abandonListening(); // nothing heard after this is a question: there is no token to ask with
    clear(conversation);
    status.textContent = "";
    unavailable.hidden = true;
    app.hidden = true;
    gate.hidden = false;
    gateMessage.textContent = message || "";
  }

  function showApp() {
    unavailable.hidden = true;
    gate.hidden = true;
    app.hidden = false;
    status.textContent = "";
    questionInput.focus();
  }

  // -- waking the assistant ---------------------------------------------------------------------

  // Sent once, as the operator signs in: it starts the two Lambdas a question passes through, so
  // the first question is not the one that waits for them. The API lists its tools and stops: no
  // model, no data, nothing against the daily limit (lambdas/ops_agent_handler.py, "The wake
  // call"). Nothing about it is shown: not that it was sent, not what came back, not a failure.
  // At most one every WARM_COOLDOWN_MS from this tab; the time of the last one is all that is
  // kept (in sessionStorage, so a reload inside the window does not send another).
  function warmUp() {
    var last = 0;
    try {
      last = Number(root.sessionStorage.getItem(WARMED_KEY)) || 0;
    } catch (err) {
      // Storage is blocked: wake once per page load, which is still at most one per sign-in.
    }
    if (!accessToken || !shouldWarm(last, Date.now())) {
      return;
    }
    try {
      root.sessionStorage.setItem(WARMED_KEY, String(Date.now()));
    } catch (err) {
      // As above.
    }
    try {
      root
        .fetch(config.askUrl, {
          method: "POST",
          headers: { Authorization: "Bearer " + accessToken, "Content-Type": "application/json" },
          body: JSON.stringify({ warm: true }),
        })
        .then(noop, noop);
    } catch (err) {
      // Never the operator's problem.
    }
  }

  // -- sign-in ---------------------------------------------------------------------------------

  function signIn() {
    var verifier = randomString(32, root.crypto);
    var state = randomString(16, root.crypto);
    pkceChallenge(verifier, root.crypto.subtle).then(
      function (challenge) {
        try {
          root.sessionStorage.setItem(VERIFIER_KEY, verifier);
          root.sessionStorage.setItem(STATE_KEY, state);
        } catch (err) {
          gateMessage.textContent = "This browser will not let the page remember the sign-in step. " + MESSAGES.signInFailed;
          return;
        }
        root.location.assign(authorizeUrl(config, state, challenge));
      },
      function () {
        gateMessage.textContent = MESSAGES.signInFailed;
      }
    );
  }

  // Runs once on load. If Cognito has just sent the browser back (?code=...&state=...), finishes
  // the sign-in; otherwise shows the gate.
  function start() {
    var params = new root.URLSearchParams(root.location.search);
    var code = params.get("code");
    var returnedState = params.get("state");
    var failed = params.get("error");

    // Whatever happens next, the verifier and state are used up: read them and remove them.
    var verifier = null;
    var expectedState = null;
    try {
      verifier = root.sessionStorage.getItem(VERIFIER_KEY);
      expectedState = root.sessionStorage.getItem(STATE_KEY);
      root.sessionStorage.removeItem(VERIFIER_KEY);
      root.sessionStorage.removeItem(STATE_KEY);
    } catch (err) {
      // Storage is blocked: there was no sign-in to finish.
    }

    if (!code && !failed) {
      showGate("");
      return;
    }

    // The code is single-use and now in hand: take it (and the state) out of the address bar and
    // the history entry before doing anything else.
    root.history.replaceState(null, "", root.location.pathname);

    if (failed || !code || !verifier || !expectedState || returnedState !== expectedState) {
      showGate(MESSAGES.signInFailed);
      return;
    }

    showGate("Signing in.");
    root
      .fetch("https://" + config.hostedUiDomain + "/oauth2/token", {
        method: "POST",
        headers: { "Content-Type": "application/x-www-form-urlencoded" },
        body: tokenRequestBody(config, code, verifier),
      })
      .then(function (response) {
        if (!response.ok) {
          throw new Error("token exchange refused");
        }
        return response.json();
      })
      .then(function (tokens) {
        if (!tokens || !isText(tokens.access_token)) {
          throw new Error("no access token");
        }
        // Only the access token is kept, and only here. The id and refresh tokens, if Cognito
        // sent any, are dropped with `tokens`.
        accessToken = tokens.access_token;
        var seconds = Number(tokens.expires_in) > 0 ? Number(tokens.expires_in) : 3600;
        tokenExpiresAt = Date.now() + seconds * 1000;
        showApp();
        warmUp();
      })
      .catch(function () {
        showGate(MESSAGES.signInFailed);
      });
  }

  function signOut() {
    showGate("");
    root.location.assign(logoutUrl(config));
  }

  // -- showing an answer -----------------------------------------------------------------------

  function copyCommand(code, button) {
    var label = button.textContent;
    function selectIt() {
      // No clipboard (an old browser, or permission refused): select the command so Ctrl+C works.
      var range = doc.createRange();
      range.selectNodeContents(code);
      var selection = root.getSelection();
      selection.removeAllRanges();
      selection.addRange(range);
      status.textContent = "Command selected. Press Ctrl+C (or Cmd+C) to copy it.";
    }
    if (root.navigator.clipboard && root.navigator.clipboard.writeText) {
      root.navigator.clipboard.writeText(code.textContent).then(function () {
        status.textContent =
          "Command copied. Run it in your own terminal" +
          (config.environment ? ", against the " + config.environment + " admin API." : ".");
        button.textContent = "Copied";
        root.setTimeout(function () {
          button.textContent = label;
        }, 2000);
      }, selectIt);
    } else {
      selectIt();
    }
  }

  function renderTurn(question, result) {
    var turn = make("article", "ask-turn");
    turn.appendChild(make("p", "ask-turn-question", "You asked: " + question));
    turn.appendChild(make("p", "ask-turn-answer", result.answer));

    // Tables first: when one was asked for ("list my topics"), it is the answer.
    result.tables.forEach(function (table) {
      var shown = renderTable(doc, table);
      if (shown) {
        turn.appendChild(shown);
      }
    });

    if (result.toolCalls.length) {
      turn.appendChild(make("h2", "", "What the assistant called"));
      var list = make("ol", "ask-tool-calls");
      result.toolCalls.forEach(function (call) {
        var item = make("li");
        var args = call && call.arguments !== undefined ? JSON.stringify(call.arguments) : "{}";
        item.appendChild(make("code", "", String(call && call.name) + " " + args));
        list.appendChild(item);
      });
      turn.appendChild(list);
    }

    if (result.findings.length) {
      // An answer to "how do I ...?" has only how-to cards: nothing was found wrong.
      var guidance = result.findings.every(isHowTo);
      turn.appendChild(make("h2", "", guidance ? "How to do it" : "Findings and suggestions"));
      result.findings.forEach(function (finding) {
        if (finding && typeof finding === "object") {
          turn.appendChild(renderCard(doc, finding, copyCommand));
        }
      });
    }
    // Newest first, so the answer just given is next to the controls.
    conversation.insertBefore(turn, conversation.firstChild);
  }

