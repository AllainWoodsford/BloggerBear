/* The operator's assistant page (ask.html): sign in, ask, hear the answer, see what to do.
   Design: docs/enhancements/alexa-plus-operator-assistant-enhancement.md, sections 3, 5 and 7.

   Sign-in is Cognito's hosted page, authorization code with PKCE (S256). The page makes a random
   verifier and state, keeps them in sessionStorage only for the trip to the hosted page and back,
   and swaps the returned code for an access token at the hosted domain's /oauth2/token.

   THE ACCESS TOKEN LIVES IN A VARIABLE AND NOWHERE ELSE: never in sessionStorage, localStorage or
   a cookie, so closing or reloading the tab signs you out. The conversation is the same: an array
   in this file, sent back as `history` with each question, gone with the tab.

   EVERYTHING THE API RETURNS IS TREATED AS TEXT FROM A STRANGER. It reaches the page through
   createElement and textContent only; nothing in this file parses a string as HTML or code. A
   suggested command is shown for the operator to copy and run in their own terminal: this page
   never runs one, and never reads one aloud. The same holds for the answers to "how do I ...?":
   a command's help in a scrolling block, a command the server built, a template (marked, with its
   <placeholders>) for one that deletes, and the topics as a table.

   Settings come from config.js (generated by Terraform) as window.OPS_ASSISTANT. Where it is
   missing, the page leaves "not available here" showing and does nothing.

   The pure parts are exported for the Node test (lambdas/tests/test_frontend_ask.py). */
