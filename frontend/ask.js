  function base64Url(bytes) {
    var binary = "";
    for (var i = 0; i < bytes.length; i++) {
      binary += String.fromCharCode(bytes[i]);
    }
    return btoa(binary).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
  }

  function randomString(byteCount, cryptoImpl) {
    var bytes = new Uint8Array(byteCount);
    cryptoImpl.getRandomValues(bytes);
    return base64Url(bytes);
  }

  // RFC 7636 section 4.2: BASE64URL(SHA256(ASCII(verifier))).
  function pkceChallenge(verifier, subtle) {
    var ascii = new Uint8Array(verifier.length);
    for (var i = 0; i < verifier.length; i++) {
      ascii[i] = verifier.charCodeAt(i);
    }
    return subtle.digest("SHA-256", ascii).then(function (digest) {
      return base64Url(new Uint8Array(digest));
    });
  }

  function isText(value) {
    return typeof value === "string" && value.trim() !== "";
  }

  // The settings as config.js gave them, or null unless every one is there and looks right.
  function readConfig(raw) {
    if (!raw || typeof raw !== "object") {
      return null;
    }
    var names = ["askUrl", "hostedUiDomain", "clientId", "scope", "redirectUri"];
    for (var i = 0; i < names.length; i++) {
      if (!isText(raw[names[i]])) {
        return null;
      }
    }
    if (raw.askUrl.indexOf("https://") !== 0 || raw.redirectUri.indexOf("https://") !== 0) {
      return null;
    }
    if (!/^[a-z0-9.-]+$/.test(raw.hostedUiDomain)) {
      return null;
    }
    return {
      askUrl: raw.askUrl,
      hostedUiDomain: raw.hostedUiDomain,
      clientId: raw.clientId,
      scope: raw.scope,
      redirectUri: raw.redirectUri,
      // Optional: which environment's pipeline this page asks about, shown so a command copied
      // from a dev card is not run against production. Anything but a short word is left out.
      environment:
        typeof raw.environment === "string" && /^[a-z][a-z0-9-]{0,15}$/.test(raw.environment) ? raw.environment : "",
    };
  }

  function query(params) {
    return Object.keys(params)
      .map(function (name) {
        return encodeURIComponent(name) + "=" + encodeURIComponent(params[name]);
      })
      .join("&");
  }

  function authorizeUrl(config, state, challenge) {
    return (
      "https://" +
      config.hostedUiDomain +
      "/oauth2/authorize?" +
      query({
        response_type: "code",
        client_id: config.clientId,
        redirect_uri: config.redirectUri,
        scope: config.scope,
        state: state,
        code_challenge: challenge,
        code_challenge_method: "S256",
      })
    );
  }

  function tokenRequestBody(config, code, verifier) {
    return query({
      grant_type: "authorization_code",
      client_id: config.clientId,
      code: code,
      redirect_uri: config.redirectUri,
      code_verifier: verifier,
    });
  }

  function logoutUrl(config) {
    return (
      "https://" +
      config.hostedUiDomain +
      "/logout?" +
      query({ client_id: config.clientId, logout_uri: config.redirectUri })
    );
  }

  // { question } trimmed and within the limit, or { error } to show instead of sending.
  function checkQuestion(text) {
    var question = typeof text === "string" ? text.trim() : "";
    if (!question) {
      return { error: "Say or type a question first." };
    }
    if (question.length > QUESTION_MAX_CHARS) {
      return { error: "That question is too long: " + QUESTION_MAX_CHARS + " characters at most." };
    }
    return { question: question };
  }

  // What goes back as `history`: the last few turns, each cut to the length the API takes. A turn
  // with no text is left out (the API refuses one).
  function buildHistory(turns) {
    var history = [];
    for (var i = 0; i < turns.length; i++) {
      var turn = turns[i];
      if (!turn || (turn.role !== "user" && turn.role !== "assistant") || !isText(turn.text)) {
        continue;
      }
      history.push({ role: turn.role, text: turn.text.trim().slice(0, TURN_MAX_CHARS) });
    }
    return history.slice(-HISTORY_MAX_TURNS);
  }

  // A finding's `where` (and anything else nested) as flat rows to show:
  // [{ label, text, untrusted }]. Everything under a key named "untrusted" is marked, however
  // deep it sits.
  function flattenRows(value, label, untrusted, rows, depth) {
    rows = rows || [];
    depth = depth || 0;
    if (value === null || value === undefined || value === "") {
      return rows;
    }
    if (typeof value !== "object" || Array.isArray(value) || depth >= 4) {
      rows.push({
        label: label || "",
        text: typeof value === "object" ? JSON.stringify(value) : String(value),
        untrusted: !!untrusted,
      });
      return rows;
    }
    Object.keys(value).forEach(function (key) {
      if (key === "untrusted") {
        flattenRows(value[key], label, true, rows, depth + 1);
      } else {
        flattenRows(value[key], label ? label + " " + key : key, untrusted, rows, depth + 1);
      }
    });
    return rows;
  }

  // What kind of card a finding gets: "fix" (a command to copy), "look" (something to look at,
  // no command) or "noticed" (no suggestion at all).
  function cardKind(finding) {
    var suggestion = finding && finding.suggestion;
    if (!suggestion || typeof suggestion !== "object") {
      return "noticed";
    }
    return isText(suggestion.command) ? "fix" : "look";
  }

  // The answer as it is spoken. The agent is told never to say a command; if one turns up in the
  // answer anyway, it is not read out.
  function spokenText(answer, findings) {
    var text = typeof answer === "string" ? answer : "";
    (Array.isArray(findings) ? findings : []).forEach(function (finding) {
      if (cardKind(finding) === "fix") {
        text = text.split(finding.suggestion.command).join("the command on screen");
      }
    });
    return text;
  }

  // A how-to card is the CLI guide's (lambdas/ops_mcp/cli_guide.py): a command's own help, or a
  // command the server built because the operator asked how. It is guidance, not something wrong.
  function isHowTo(finding) {
    return !!finding && finding.kind === "how_to";
  }

  // A template for a command that deletes or takes something down. The server never fills one in:
  // it carries <placeholders>, and the page says so before the operator copies it.
  function isDestructive(finding) {
    return !!finding && finding.destructive === true;
  }

  // The label of a card's first row: what was noticed, or what the operator asked how to do.
  function cardHeading(finding) {
    return isHowTo(finding) ? "How to" : "Noticed";
  }

  // A table from the API as the page will show it: { title, columns, rows } with every cell text
  // and every row as wide as the columns, or null if it is not a table. The API cuts tables to
  // size (lambdas/ops_agent/policy.py); the same limits are held here, for a response that did not
  // come from it.
  function tableModel(table) {
    if (!table || typeof table !== "object" || !Array.isArray(table.columns) || !Array.isArray(table.rows)) {
      return null;
    }
    var columns = table.columns.slice(0, TABLE_MAX_COLUMNS).map(cellText);
    if (!columns.length) {
      return null;
    }
    var rows = [];
    table.rows.slice(0, TABLE_MAX_ROWS).forEach(function (row) {
      if (!Array.isArray(row)) {
        return;
      }
      var cells = [];
      for (var i = 0; i < columns.length; i++) {
        cells.push(cellText(row[i]));
      }
      rows.push(cells);
    });
    return { title: isText(table.title) ? table.title.trim() : "Table", columns: columns, rows: rows };
  }

  function cellText(value) {
    if (typeof value === "number" && isFinite(value)) {
      return String(value);
    }
    return typeof value === "string" ? value : "";
  }

  // ---------------------------------------------------------------------------------------------
  // Building the page's nodes. Each takes the document, so the Node test can hand it a stand-in
  // and see what would be shown. createElement and textContent only: whatever the API sent is
  // text here, never markup.
  // ---------------------------------------------------------------------------------------------

  function makeNode(doc, tag, className, text) {
    var node = doc.createElement(tag);
    if (className) {
      node.className = className;
    }
    if (text !== undefined && text !== null) {
      node.textContent = String(text);
    }
    return node;
  }

  function appendRow(doc, list, label, text, untrusted) {
    list.appendChild(makeNode(doc, "dt", "", label));
    var dd = makeNode(doc, "dd", untrusted ? "ask-untrusted" : "");
    if (untrusted) {
      dd.appendChild(makeNode(doc, "span", "ask-untrusted-mark", "Unverified"));
    }
    dd.appendChild(doc.createTextNode(text));
    list.appendChild(dd);
  }

  // Whether a wake call may be sent now: not when one went out less than WARM_COOLDOWN_MS ago.
  // A stored time from the future (a changed clock) does not hold it back.
  function shouldWarm(lastWarmedAt, now) {
    var last = Number(lastWarmedAt) || 0;
    return !(last > 0 && now >= last && now - last < WARM_COOLDOWN_MS);
  }

  function noop() {}

  // One finding as a card. `onCopy(code, button)` is called when Copy is pressed, with the node
  // that holds the command: what is copied is that node's text, so a template is copied with its
  // placeholders as they are.
  function renderCard(doc, finding, onCopy) {
    var howTo = isHowTo(finding);
    var destructive = isDestructive(finding);
    var card = makeNode(doc, "div", "ask-card" + (howTo ? " ask-card-how-to" : "") + (destructive ? " ask-card-destructive" : ""));
    var kind = cardKind(finding);
    var suggestion = kind === "noticed" ? null : finding.suggestion;

    var top = makeNode(doc, "dl");
    appendRow(doc, top, cardHeading(finding), isText(finding.noticed) ? finding.noticed : "(no description)", false);
    var where = flattenRows(finding.where, "", false);
    flattenRows(finding.untrusted, "", true, where);
    where.forEach(function (row, index) {
      var text = row.label ? row.label + ": " + row.text : row.text;
      appendRow(doc, top, index === 0 ? (howTo ? "About" : "Where") : "", text, row.untrusted);
    });
    if (suggestion && isText(suggestion.action)) {
      appendRow(doc, top, kind === "fix" ? (howTo ? "Next" : "Suggested") : "Look at", suggestion.action, false);
    }
    card.appendChild(top);

    if (destructive) {
      var warning = makeNode(doc, "p", "ask-warning");
      warning.setAttribute("role", "note");
      warning.appendChild(makeNode(doc, "strong", "", "Template, not filled in. "));
      warning.appendChild(
        doc.createTextNode(
          isText(finding.warning)
            ? finding.warning
            : "This command deletes something or takes it down. Replace each <placeholder> yourself before you run it."
        )
      );
      card.appendChild(warning);
    } else if (isText(finding.warning) || (suggestion && isText(suggestion.warning))) {
      // Every Admin CLI command the assistant suggests carries this: check it before running it.
      var check = makeNode(doc, "p", "ask-warning ask-warning-check");
      check.setAttribute("role", "note");
      check.appendChild(makeNode(doc, "strong", "", "Check before you run it. "));
      check.appendChild(doc.createTextNode(isText(finding.warning) ? finding.warning : suggestion.warning));
      card.appendChild(check);
    }

    if (kind === "fix") {
      var block = makeNode(doc, "div", "ask-command");
      var pre = makeNode(doc, "pre");
      var code = makeNode(doc, "code", "", suggestion.command);
      pre.appendChild(code);
      var copy = makeNode(doc, "button", "ask-copy", destructive ? "Copy template" : "Copy");
      copy.type = "button";
      copy.setAttribute(
        "aria-label",
        destructive ? "Copy the template, with its placeholders" : howTo ? "Copy the command" : "Copy the suggested command"
      );
      copy.addEventListener("click", function () {
        onCopy(code, copy);
      });
      block.appendChild(pre);
      block.appendChild(copy);
      card.appendChild(block);
    }
    if (suggestion && isText(suggestion.what_it_does)) {
      var bottom = makeNode(doc, "dl");
      appendRow(doc, bottom, "What it does", suggestion.what_it_does, false);
      card.appendChild(bottom);
    }
    if (isText(finding.help)) {
      // The command's own --help, as the CLI prints it: fixed-width, and scrollable (by keyboard
      // too) where it is wider or longer than the card.
      var help = makeNode(doc, "pre", "ask-help", finding.help);
      help.setAttribute("tabindex", "0");
      help.setAttribute("role", "region");
      help.setAttribute("aria-label", "Help text" + (isText(finding.noticed) ? " for " + finding.noticed : ""));
      card.appendChild(help);
    }
    return card;
  }

  // One table as a real <table>, inside a region that scrolls sideways on a narrow screen. Null
  // for something that is not a table.
  function renderTable(doc, table) {
    var model = tableModel(table);
    if (!model) {
      return null;
    }
    var wrap = makeNode(doc, "div", "ask-table-wrap");
    wrap.setAttribute("tabindex", "0");
    wrap.setAttribute("role", "region");
    wrap.setAttribute("aria-label", model.title);
    var node = makeNode(doc, "table", "ask-table");
    node.appendChild(makeNode(doc, "caption", "", model.title));
    var head = makeNode(doc, "thead");
    var headRow = makeNode(doc, "tr");
    model.columns.forEach(function (column) {
      var th = makeNode(doc, "th", "", column);
      th.setAttribute("scope", "col");
      headRow.appendChild(th);
    });
    head.appendChild(headRow);
    node.appendChild(head);
    var body = makeNode(doc, "tbody");
    model.rows.forEach(function (row) {
      var tr = makeNode(doc, "tr");
      row.forEach(function (cell, index) {
        var td = makeNode(doc, index === 0 ? "th" : "td", "", cell);
        if (index === 0) {
          td.setAttribute("scope", "row");
        }
        tr.appendChild(td);
      });
      body.appendChild(tr);
    });
    node.appendChild(body);
    wrap.appendChild(node);
    return wrap;
  }

  // ---------------------------------------------------------------------------------------------
  // The voice: the pure parts. (Recognition and speech themselves are the browser's, below.)
  // ---------------------------------------------------------------------------------------------

  // The language tag for recognition and speech: the browser's own English tag ("en-AU"), else
  // "en-US". Never <html lang>'s bare "en": Safari's recognition wants a full tag.
  function speechLang(navigatorLanguage) {
    var tag = typeof navigatorLanguage === "string" ? navigatorLanguage.trim() : "";
    return /^en-[A-Za-z]{2,3}$/.test(tag) ? tag : "en-US";
  }

  // An answer as the pieces it is spoken in: whole sentences, joined while they fit in maxChars,
  // and a sentence longer than that cut at its last space that fits. Chrome's online voices stop
  // about 15 seconds into one utterance, so a briefing spoken as one would be cut off.
  function speechChunks(text, maxChars) {
    var limit = maxChars > 20 ? maxChars : 20;
    var words = typeof text === "string" ? text.replace(/\s+/g, " ").trim() : "";
    if (!words) {
      return [];
    }
    // A sentence ends at a stop followed by a space or the end, never at one inside a word or a
    // number: "US$12.40" split at its point is spoken "twelve dollars. forty".
    var sentences = words.match(/\S.*?(?:[.!?]+(?=\s|$)|$)/g) || [words];
    var chunks = [];
    var current = "";
    sentences.forEach(function (sentence) {
      var piece = sentence.trim();
      while (piece.length > limit) {
        var cut = piece.lastIndexOf(" ", limit);
        if (cut <= 0) {
          cut = limit;
        }
        if (current) {
          chunks.push(current);
          current = "";
        }
        chunks.push(piece.slice(0, cut).trim());
        piece = piece.slice(cut).trim();
      }
      if (!piece) {
        return;
      }
      if (current && current.length + 1 + piece.length > limit) {
        chunks.push(current);
        current = piece;
      } else {
        current = current ? current + " " + piece : piece;
      }
    });
    if (current) {
      chunks.push(current);
    }
    return chunks;
  }

