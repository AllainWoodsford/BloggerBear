  function base64Url(bytes) {
    var binary = "";
    for (var i = 0; i < bytes.length; i++) {
      binary += String.fromCharCode(bytes[i]);
    }
    return btoa(binary).replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
  }

  function randomString(byteCount, cryptoImpl) {
    var bytes = new Uint8Array(byteCount);
    cryptoImpl.getRandomValues(bytes);
    return base64Url(bytes);
  }

  // RFC 7636 section 4.2: BASE64URL(SHA256(ASCII(verifier))).
  function pkceChallenge(verifier, subtle) {
    var ascii = new Uint8Array(verifier.length);
    for (var i = 0; i < verifier.length; i++) {
      ascii[i] = verifier.charCodeAt(i);
    }
    return subtle.digest("SHA-256", ascii).then(function (digest) {
      return base64Url(new Uint8Array(digest));
    });
  }

  function isText(value) {
    return typeof value === "string" && value.trim() !== "";
  }

  // The settings as config.js gave them, or null unless every one is there and looks right.
  function readConfig(raw) {
    if (!raw || typeof raw !== "object") {
      return null;
    }
    var names = ["askUrl", "hostedUiDomain", "clientId", "scope", "redirectUri"];
    for (var i = 0; i < names.length; i++) {
      if (!isText(raw[names[i]])) {
        return null;
      }
    }
    if (raw.askUrl.indexOf("https://") !== 0 || raw.redirectUri.indexOf("https://") !== 0) {
      return null;
    }
    if (!/^[a-z0-9.-]+$/.test(raw.hostedUiDomain)) {
      return null;
    }
    return {
      askUrl: raw.askUrl,
      hostedUiDomain: raw.hostedUiDomain,
      clientId: raw.clientId,
      scope: raw.scope,
      redirectUri: raw.redirectUri,
      // Optional: which environment's pipeline this page asks about, shown so a command copied
      // from a dev card is not run against production. Anything but a short word is left out.
      environment:
        typeof raw.environment === "string" && /^[a-z][a-z0-9-]{0,15}$/.test(raw.environment) ? raw.environment : "",
    };
  }

  function query(params) {
    return Object.keys(params)
      .map(function (name) {
        return encodeURIComponent(name) + "=" + encodeURIComponent(params[name]);
      })
      .join("&");
  }

  function authorizeUrl(config, state, challenge) {
    return (
      "https://" +
      config.hostedUiDomain +
      "/oauth2/authorize?" +
      query({
        response_type: "code",
        client_id: config.clientId,
        redirect_uri: config.redirectUri,
        scope: config.scope,
        state: state,
        code_challenge: challenge,
        code_challenge_method: "S256",
      })
    );
  }

  function tokenRequestBody(config, code, verifier) {
    return query({
      grant_type: "authorization_code",
      client_id: config.clientId,
      code: code,
      redirect_uri: config.redirectUri,
      code_verifier: verifier,
    });
  }

  function logoutUrl(config) {
    return (
      "https://" +
      config.hostedUiDomain +
      "/logout?" +
      query({ client_id: config.clientId, logout_uri: config.redirectUri })
    );
  }

  // { question } trimmed and within the limit, or { error } to show instead of sending.
  function checkQuestion(text) {
    var question = typeof text === "string" ? text.trim() : "";
    if (!question) {
      return { error: "Say or type a question first." };
    }
    if (question.length > QUESTION_MAX_CHARS) {
      return { error: "That question is too long: " + QUESTION_MAX_CHARS + " characters at most." };
    }
    return { question: question };
  }

  // What goes back as `history`: the last few turns, each cut to the length the API takes. A turn
  // with no text is left out (the API refuses one).
  function buildHistory(turns) {
    var history = [];
    for (var i = 0; i < turns.length; i++) {
      var turn = turns[i];
      if (!turn || (turn.role !== "user" && turn.role !== "assistant") || !isText(turn.text)) {
        continue;
      }
      history.push({ role: turn.role, text: turn.text.trim().slice(0, TURN_MAX_CHARS) });
    }
    return history.slice(-HISTORY_MAX_TURNS);
  }

  // A finding's `where` (and anything else nested) as flat rows to show:
  // [{ label, text, untrusted }]. Everything under a key named "untrusted" is marked, however
  // deep it sits.
  function flattenRows(value, label, untrusted, rows, depth) {
    rows = rows || [];
    depth = depth || 0;
    if (value === null || value === undefined || value === "") {
      return rows;
    }
    if (typeof value !== "object" || Array.isArray(value) || depth >= 4) {
      rows.push({
        label: label || "",
        text: typeof value === "object" ? JSON.stringify(value) : String(value),
        untrusted: !!untrusted,
      });
      return rows;
    }
    Object.keys(value).forEach(function (key) {
      if (key === "untrusted") {
        flattenRows(value[key], label, true, rows, depth + 1);
      } else {
        flattenRows(value[key], label ? label + " " + key : key, untrusted, rows, depth + 1);
      }
    });
    return rows;
  }

  // What kind of card a finding gets: "fix" (a command to copy), "look" (something to look at,
  // no command) or "noticed" (no suggestion at all).
  function cardKind(finding) {
    var suggestion = finding && finding.suggestion;
    if (!suggestion || typeof suggestion !== "object") {
      return "noticed";
    }
    return isText(suggestion.command) ? "fix" : "look";
  }

  // The answer as it is spoken. The agent is told never to say a command; if one turns up in the
  // answer anyway, it is not read out.
  function spokenText(answer, findings) {
    var text = typeof answer === "string" ? answer : "";
    (Array.isArray(findings) ? findings : []).forEach(function (finding) {
      if (cardKind(finding) === "fix") {
        text = text.split(finding.suggestion.command).join("the command on screen");
      }
    });
    return text;
  }

  // A how-to card is the CLI guide's (lambdas/ops_mcp/cli_guide.py): a command's own help, or a
  // command the server built because the operator asked how. It is guidance, not something wrong.
  function isHowTo(finding) {
    return !!finding && finding.kind === "how_to";
  }

  // A template for a command that deletes or takes something down. The server never fills one in:
  // it carries <placeholders>, and the page says so before the operator copies it.
  function isDestructive(finding) {
    return !!finding && finding.destructive === true;
  }

  // The label of a card's first row: what was noticed, or what the operator asked how to do.
  function cardHeading(finding) {
    return isHowTo(finding) ? "How to" : "Noticed";
  }

  // A table from the API as the page will show it: { title, columns, rows } with every cell text
  // and every row as wide as the columns, or null if it is not a table. The API cuts tables to
  // size (lambdas/ops_agent/policy.py); the same limits are held here, for a response that did not
  // come from it.
  function tableModel(table) {
    if (!table || typeof table !== "object" || !Array.isArray(table.columns) || !Array.isArray(table.rows)) {
      return null;
    }
    var columns = table.columns.slice(0, TABLE_MAX_COLUMNS).map(cellText);
    if (!columns.length) {
      return null;
    }
    var rows = [];
    table.rows.slice(0, TABLE_MAX_ROWS).forEach(function (row) {
      if (!Array.isArray(row)) {
        return;
      }
      var cells = [];
      for (var i = 0; i < columns.length; i++) {
        cells.push(cellText(row[i]));
      }
      rows.push(cells);
    });
    return { title: isText(table.title) ? table.title.trim() : "Table", columns: columns, rows: rows };
  }

  function cellText(value) {
    if (typeof value === "number" && isFinite(value)) {
      return String(value);
    }
    return typeof value === "string" ? value : "";
  }

  // ---------------------------------------------------------------------------------------------
  // Building the page's nodes. Each takes the document, so the Node test can hand it a stand-in
  // and see what would be shown. createElement and textContent only: whatever the API sent is
  // text here, never markup.
