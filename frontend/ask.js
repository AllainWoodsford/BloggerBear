  // -- speaking --------------------------------------------------------------------------------
  // An answer is spoken a sentence or two at a time (speechChunks). Every utterance is held in
  // `speechQueue` until it ends: Chrome can collect one nobody refers to and stop mid-word.

  var LANG = speechLang(root.navigator && root.navigator.language);
  var synth = root.speechSynthesis && root.SpeechSynthesisUtterance ? root.speechSynthesis : null;
  var speechQueue = [];
  var speechTimer = 0;
  var speechUnlocked = false;
  var blockedSpeech = ""; // an answer the browser refused to speak until the next tap
  var voice = null;

  function chooseVoice() {
    if (synth) {
      voice = pickVoice(synth.getVoices(), LANG);
    }
  }

  function stopSpeaking() {
    root.clearTimeout(speechTimer);
    speechQueue = [];
    // Cancel only what is there: Chrome can drop the next utterance after a needless cancel().
    if (synth && (synth.speaking || synth.pending)) {
      synth.cancel();
    }
  }

  // Speaks whatever it is given, muted or not (the voice test uses it directly).
  // `onDone` (optional) is called once, when the last piece has been spoken (or failed), so the
  // voice test can start listening after its sample and not over it: listening cancels speech.
  function say(text, onDone) {
    if (!synth) {
      return false;
    }
    stopSpeaking();
    var chunks = speechChunks(text, SPEECH_CHUNK_CHARS);
    if (!chunks.length) {
      return false;
    }
    var done = false;
    function finish() {
      if (!done) {
        done = true;
        if (onDone) {
          onDone();
        }
      }
    }
    if (!voice) {
      chooseVoice();
    }
    // On the next tick, never in the same one as cancel(): Chrome drops that utterance.
    speechTimer = root.setTimeout(function () {
      chunks.forEach(function (chunk, position) {
        var utterance = new root.SpeechSynthesisUtterance(chunk);
        utterance.lang = LANG;
        if (voice) {
          utterance.voice = voice;
        }
        utterance.onend = utterance.onerror = function (event) {
          var index = speechQueue.indexOf(utterance);
          if (index >= 0) {
            speechQueue.splice(index, 1);
          }
          if (event && event.type === "error" && event.error === "not-allowed") {
            // The browser wants a tap before it will speak (iOS): keep the answer, and say it
            // when the operator next taps or clicks anything (unlockSpeech).
            blockedSpeech = text;
            speechUnlocked = false;
            status.textContent = "Tap anywhere on the page to hear the answer.";
          }
          if (position === chunks.length - 1) {
            finish();
          }
        };
        speechQueue.push(utterance);
        synth.speak(utterance);
      });
    }, SPEECH_DELAY_MS);
    // A browser that never reports the end must not leave the caller waiting for ever.
    root.setTimeout(finish, SPEECH_DONE_FALLBACK_MS);
    return true;
  }

  function speak(text) {
    if (muted || !text) {
      return;
    }
    say(text);
  }

  // iOS speaks only if speech was first started from a tap; an answer arrives seconds after one.
  // The first tap on a control (not the talk button, whose tap starts the microphone) speaks one
  // silent space, and later answers are then allowed.
  //
  // On click (and Enter or Space), not pointerdown: a touch's pointerdown is not a user activation,
  // so iOS would refuse the very utterance meant to unlock it. Not on the talk button, whose tap
  // starts the microphone. Marked done only when the silent utterance actually starts; an answer
  // that was refused in the meantime (blockedSpeech) is spoken now, from this tap.
  function unlockSpeech(event) {
    if (!synth || (event && event.target && event.target.closest && event.target.closest("#ask-talk"))) {
      return;
    }
    if (blockedSpeech) {
      var text = blockedSpeech;
      blockedSpeech = "";
      speechUnlocked = true;
      speak(text);
      return;
    }
    if (speechUnlocked) {
      return;
    }
    var silent = new root.SpeechSynthesisUtterance(" ");
    silent.volume = 0;
    silent.onstart = function () {
      speechUnlocked = true;
    };
    synth.speak(silent);
  }

  // Back to the gate: forgets the token and the conversation.
  function showGate(message) {
    accessToken = null;
    tokenExpiresAt = 0;
    turns = [];
    stopSpeaking();
    stopListening();
    clear(conversation);
    status.textContent = "";
    unavailable.hidden = true;
    app.hidden = true;
    gate.hidden = false;
    gateMessage.textContent = message || "";
  }

  function showApp() {
    unavailable.hidden = true;
    gate.hidden = true;
    app.hidden = false;
    status.textContent = "";
    questionInput.focus();
  }

  // -- sign-in ---------------------------------------------------------------------------------

  function signIn() {
    var verifier = randomString(32, root.crypto);
    var state = randomString(16, root.crypto);
    pkceChallenge(verifier, root.crypto.subtle).then(
      function (challenge) {
        try {
          root.sessionStorage.setItem(VERIFIER_KEY, verifier);
          root.sessionStorage.setItem(STATE_KEY, state);
        } catch (err) {
          gateMessage.textContent = "This browser will not let the page remember the sign-in step. " + MESSAGES.signInFailed;
          return;
        }
        root.location.assign(authorizeUrl(config, state, challenge));
      },
      function () {
        gateMessage.textContent = MESSAGES.signInFailed;
      }
    );
  }

  // Runs once on load. If Cognito has just sent the browser back (?code=...&state=...), finishes
  // the sign-in; otherwise shows the gate.
  function start() {
    var params = new root.URLSearchParams(root.location.search);
    var code = params.get("code");
    var returnedState = params.get("state");
    var failed = params.get("error");

    // Whatever happens next, the verifier and state are used up: read them and remove them.
    var verifier = null;
    var expectedState = null;
    try {
      verifier = root.sessionStorage.getItem(VERIFIER_KEY);
      expectedState = root.sessionStorage.getItem(STATE_KEY);
      root.sessionStorage.removeItem(VERIFIER_KEY);
      root.sessionStorage.removeItem(STATE_KEY);
    } catch (err) {
      // Storage is blocked: there was no sign-in to finish.
    }

    if (!code && !failed) {
      showGate("");
      return;
    }

    // The code is single-use and now in hand: take it (and the state) out of the address bar and
    // the history entry before doing anything else.
    root.history.replaceState(null, "", root.location.pathname);

    if (failed || !code || !verifier || !expectedState || returnedState !== expectedState) {
      showGate(MESSAGES.signInFailed);
      return;
    }

    showGate("Signing in.");
    root
      .fetch("https://" + config.hostedUiDomain + "/oauth2/token", {
        method: "POST",
        headers: { "Content-Type": "application/x-www-form-urlencoded" },
        body: tokenRequestBody(config, code, verifier),
      })
      .then(function (response) {
        if (!response.ok) {
          throw new Error("token exchange refused");
        }
        return response.json();
      })
      .then(function (tokens) {
        if (!tokens || !isText(tokens.access_token)) {
          throw new Error("no access token");
        }
        // Only the access token is kept, and only here. The id and refresh tokens, if Cognito
        // sent any, are dropped with `tokens`.
        accessToken = tokens.access_token;
        var seconds = Number(tokens.expires_in) > 0 ? Number(tokens.expires_in) : 3600;
        tokenExpiresAt = Date.now() + seconds * 1000;
        showApp();
      })
      .catch(function () {
        showGate(MESSAGES.signInFailed);
      });
  }

  function signOut() {
    showGate("");
    root.location.assign(logoutUrl(config));
  }

  // -- showing an answer -----------------------------------------------------------------------

  function copyCommand(code, button) {
    var label = button.textContent;
    function selectIt() {
      // No clipboard (an old browser, or permission refused): select the command so Ctrl+C works.
      var range = doc.createRange();
      range.selectNodeContents(code);
      var selection = root.getSelection();
      selection.removeAllRanges();
      selection.addRange(range);
      status.textContent = "Command selected. Press Ctrl+C (or Cmd+C) to copy it.";
    }
    if (root.navigator.clipboard && root.navigator.clipboard.writeText) {
      root.navigator.clipboard.writeText(code.textContent).then(function () {
        status.textContent =
          "Command copied. Run it in your own terminal" +
          (config.environment ? ", against the " + config.environment + " admin API." : ".");
        button.textContent = "Copied";
        root.setTimeout(function () {
          button.textContent = label;
        }, 2000);
      }, selectIt);
    } else {
      selectIt();
    }
  }

  function renderTurn(question, result) {
    var turn = make("article", "ask-turn");
    turn.appendChild(make("p", "ask-turn-question", "You asked: " + question));
    turn.appendChild(make("p", "ask-turn-answer", result.answer));

    // Tables first: when one was asked for ("list my topics"), it is the answer.
    result.tables.forEach(function (table) {
      var shown = renderTable(doc, table);
      if (shown) {
        turn.appendChild(shown);
      }
    });

    if (result.toolCalls.length) {
      turn.appendChild(make("h2", "", "What the assistant called"));
      var list = make("ol", "ask-tool-calls");
      result.toolCalls.forEach(function (call) {
        var item = make("li");
        var args = call && call.arguments !== undefined ? JSON.stringify(call.arguments) : "{}";
        item.appendChild(make("code", "", String(call && call.name) + " " + args));
        list.appendChild(item);
      });
      turn.appendChild(list);
    }

    if (result.findings.length) {
      // An answer to "how do I ...?" has only how-to cards: nothing was found wrong.
      var guidance = result.findings.every(isHowTo);
      turn.appendChild(make("h2", "", guidance ? "How to do it" : "Findings and suggestions"));
      result.findings.forEach(function (finding) {
        if (finding && typeof finding === "object") {
          turn.appendChild(renderCard(doc, finding, copyCommand));
        }
      });
    }
    // Newest first, so the answer just given is next to the controls.
    conversation.insertBefore(turn, conversation.firstChild);
  }

  // -- asking ----------------------------------------------------------------------------------

  function setBusy(value) {
    busy = value;
    ["ask-send", "ask-briefing", "ask-new", "ask-talk"].forEach(function (id) {
      el(id).disabled = value;
    });
    conversation.setAttribute("aria-busy", value ? "true" : "false");
  }

  function errorFrom(response) {
    return response.json().then(
      function (body) {
        return body && isText(body.error) ? body.error : "";
      },
      function () {
        return "";
      }
    );
  }

  function ask(text) {
    if (busy) {
      return;
    }
    stopSpeaking(); // a new question interrupts the last answer
    var checked = checkQuestion(text);
    if (checked.error) {
      status.textContent = checked.error;
      return;
    }
    if (!accessToken || Date.now() >= tokenExpiresAt) {
      showGate(MESSAGES.expired);
      return;
    }

    var question = checked.question;
    var controller = root.AbortController ? new root.AbortController() : null;
    var timer = root.setTimeout(function () {
      if (controller) {
        controller.abort();
      }
    }, ASK_TIMEOUT_MS);
    setBusy(true);
    status.textContent = MESSAGES.busy;

    root
      .fetch(config.askUrl, {
        method: "POST",
        headers: { Authorization: "Bearer " + accessToken, "Content-Type": "application/json" },
        body: JSON.stringify({ question: question, history: buildHistory(turns) }),
        signal: controller ? controller.signal : undefined,
      })
      .then(function (response) {
        if (response.status === 401) {
          showGate(MESSAGES.expired);
          return null;
        }
        if (response.status === 403) {
          status.textContent = MESSAGES.forbidden;
          return null;
        }
        if (response.status === 429) {
          // The daily cap (the API's own words), or API Gateway's throttle (no words of its own).
          return errorFrom(response).then(function (reason) {
            status.textContent = reason || "Too many questions just now. Try again in a moment.";
            return null;
          });
        }
        if (response.status === 400) {
          return errorFrom(response).then(function (reason) {
            status.textContent = "The assistant did not take that question" + (reason ? ": " + reason : ".");
            return null;
          });
        }
        if (!response.ok) {
          status.textContent = MESSAGES.failed; // 502, and anything else that is not an answer
          return null;
        }
        return response.json().then(function (body) {
          if (!body || typeof body.answer !== "string") {
            status.textContent = MESSAGES.failed;
            return null;
          }
          var result = {
            answer: body.answer,
            toolCalls: Array.isArray(body.tool_calls) ? body.tool_calls : [],
            findings: Array.isArray(body.findings) ? body.findings : [],
            tables: Array.isArray(body.tables) ? body.tables : [],
          };
          turns.push({ role: "user", text: question });
          turns.push({ role: "assistant", text: result.answer });
          status.textContent = "";
          questionInput.value = "";
          renderTurn(question, result);
          speak(spokenText(result.answer, result.findings));
          return null;
        });
      })
      .catch(function () {
        status.textContent = MESSAGES.network;
      })
      .then(function () {
        root.clearTimeout(timer);
        setBusy(false);
      });
  }

  function newBriefing() {
    turns = [];
    stopSpeaking();
    clear(conversation);
    status.textContent = "Cleared. The next question starts a new briefing.";
    questionInput.value = "";
    questionInput.focus();
  }

  function toggleMute() {
    muted = !muted;
    if (muted) {
      stopSpeaking();
    }
    muteButton.setAttribute("aria-pressed", muted ? "true" : "false");
    muteButton.textContent = muted ? "Unmute voice" : "Mute voice";
  }

  // -- talking -------------------------------------------------------------------------------
  // Tap to start and tap again to stop, or let the browser stop when you stop speaking; or hold
  // (pointer, Space or Enter) and let go to finish. The words are shown as they are heard, and
  // the question is asked once recognition ends with something heard.

  var Recognition = root.SpeechRecognition || root.webkitSpeechRecognition;
  var recognition = null;
  var listening = false;
  var pressedAt = 0; // when the current press began; 0 when nothing is held
  var pressStarted = false; // whether that press was the one that started listening
  var lastPressAt = 0; // when a pointer or key press was last dealt with, to ignore its own click

  function setListening(value) {
    listening = value;
    talkButton.setAttribute("aria-pressed", value ? "true" : "false");
    talkButton.textContent = value ? "Listening. Press to stop" : "Push to talk";
  }

  // Starts the microphone. `onHeard(text)` gets what was said once recognition ends: by default
  // the question is asked; the voice test only reports it.
  function startListening(onHeard) {
    if (listening || busy || !Recognition) {
      return;
    }
    stopSpeaking();
    var heard = "";
    var failed = false;
    var current = new Recognition();
    recognition = current;
    current.lang = LANG;
    current.interimResults = true; // shown as they come, so it is clear the microphone is working
    current.continuous = false;
    current.maxAlternatives = 1;
    current.onresult = function (event) {
      var finalText = "";
      var interim = "";
      var results = event.results || [];
      for (var i = 0; i < results.length; i++) {
        var best = results[i] && results[i][0];
        var text = best && typeof best.transcript === "string" ? best.transcript : "";
        if (results[i].isFinal === false) {
          interim += text;
        } else {
          finalText += text;
        }
      }
      heard = finalText.trim();
      questionInput.value = (finalText + interim).trim();
      status.textContent = "Heard: " + questionInput.value;
    };
    current.onerror = function (event) {
      failed = true;
      var message = recognitionMessage(event && event.error);
      if (message) {
        status.textContent = message;
      }
    };
    current.onend = function () {
      if (recognition === current) {
        recognition = null;
      }
      setListening(false);
      if (heard) {
        (onHeard || ask)(heard);
      } else if (!failed) {
        status.textContent = recognitionMessage("no-speech");
      }
    };
    try {
      current.start();
      setListening(true);
      status.textContent = "Listening.";
    } catch (err) {
      recognition = null;
      setListening(false);
      status.textContent = recognitionMessage("");
    }
  }

  function stopListening() {
    if (listening && recognition) {
      recognition.stop(); // delivers what was heard so far, then onend
    }
  }

  function pressDown() {
    if (pressedAt) {
      return; // a held key repeats
    }
    pressedAt = Date.now();
    lastPressAt = pressedAt;
    pressStarted = !listening;
    if (listening) {
      stopListening();
    } else {
      startListening();
    }
  }

  function pressUp() {
    if (!pressedAt) {
      return;
    }
    var held = Date.now() - pressedAt;
    pressedAt = 0;
    lastPressAt = Date.now();
    // A real hold ends the question on release. A tap leaves it listening until the next press.
    if (pressStarted && held >= HOLD_MS) {
      stopListening();
    }
  }

  // The browser took the pointer (a scroll, or a long press on a phone): that is not the
  // operator letting go, so the microphone stays on until they tap again or stop speaking.
  function pressCancelled() {
    pressedAt = 0;
    lastPressAt = Date.now();
  }

  function isTalkKey(event) {
    return event.key === " " || event.key === "Spacebar" || event.key === "Enter";
  }

  function wireTalkButton() {
    if (!Recognition) {
      el("ask-no-speech").hidden = false;
      return;
    }
    talkButton.hidden = false;
    el("ask-talk-hint").hidden = false;

    talkButton.addEventListener("pointerdown", function (event) {
      if (event.button === 0) {
        pressDown();
      }
    });
    talkButton.addEventListener("pointerup", pressUp);
    talkButton.addEventListener("pointercancel", pressCancelled);
    talkButton.addEventListener("pointerleave", function (event) {
      // A mouse dragged off the button lets go of it; a finger lifting off a screen also
      // "leaves", after its pointerup, and is already dealt with.
      if (event.pointerType === "mouse") {
        pressUp();
      }
    });
    talkButton.addEventListener("contextmenu", function (event) {
      event.preventDefault(); // a long press must not open a menu
    });
    talkButton.addEventListener("keydown", function (event) {
      if (isTalkKey(event)) {
        event.preventDefault(); // Space must not scroll the page
        pressDown();
      }
    });
    talkButton.addEventListener("keyup", function (event) {
      if (isTalkKey(event)) {
        event.preventDefault();
        pressUp();
      }
    });
    // A click with no pointer or key press just before it comes from assistive technology (a
    // screen reader's "activate"): treat it as a tap. One that follows a press is that press.
    talkButton.addEventListener("click", function () {
      if (Date.now() - lastPressAt < CLICK_AFTER_PRESS_MS) {
        return;
      }
      if (listening) {
        stopListening();
      } else {
        startListening();
      }
    });
  }

  // -- the voice test --------------------------------------------------------------------------
  // Says which part of the voice works here: speaking, the microphone's permission, and
  // recognition. Each line is the page's own text, or what the browser heard.

  function report(lines) {
    var list = el("ask-voice-report");
    clear(list);
    lines.forEach(function (line) {
      list.appendChild(make("li", "", line));
    });
    list.hidden = false;
  }

  function testVoice() {
    if (busy || listening) {
      return;
    }
    var lines = [];
    lines.push(
      synth
        ? "Speaking: the browser can speak answers" + (muted ? " (the voice is muted for answers)." : ".") + " You should hear a short sentence now."
        : "Speaking: this browser cannot speak answers. They are shown as text."
    );
    // The test button's own click: the browser lets the page speak from it.
    var sampleDone = false;
    var afterSample = null;
    function whenSampleDone(next) {
      if (sampleDone) {
        next();
      } else {
        afterSample = next;
      }
    }
    var speaking = say("This is how the assistant's answers will sound.", function () {
      sampleDone = true;
      if (afterSample) {
        var next = afterSample;
        afterSample = null;
        next();
      }
    });
    if (!speaking) {
      sampleDone = true;
    }
    if (!Recognition) {
      lines.push("Listening: this browser has no speech recognition. Type your questions; Chrome or Edge can listen.");
      report(lines);
      return;
    }
    var permissions = root.navigator && root.navigator.permissions;
    var checked = permissions && permissions.query ? permissions.query({ name: "microphone" }) : null;
    var listen = function (state) {
      if (state === "denied") {
        lines.push("Microphone: blocked for this page. Allow it in the site settings (the icon beside the address).");
        report(lines);
        return;
      }
      lines.push(
        "Microphone: " +
          (state === "granted" ? "allowed." : "the browser will ask; allow it.") +
          " Say something short after the sentence ends; the words heard will appear here."
      );
      report(lines);
      // After the sample has been spoken: listening cancels speech, so a fixed wait could cut it off.
      whenSampleDone(function () {
        startListening(function (heard) {
          lines.push("Listening works. Heard: " + heard);
          report(lines);
          status.textContent = "Voice test finished.";
        });
      });
    };
    if (checked && checked.then) {
      checked.then(
        function (result) {
          listen(result && result.state);
        },
        function () {
          listen("");
        }
      );
    } else {
      listen("");
    }
  }

