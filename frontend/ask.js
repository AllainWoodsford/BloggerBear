    expired: "Your sign-in has expired. Sign in again to carry on.",
    forbidden: "The assistant is switched off or not available from here.",
    failed: "The assistant could not answer just now. Try again in a moment.",
    network:
      "Could not reach the assistant. Check your connection; it may also be switched off or not available from here.",
